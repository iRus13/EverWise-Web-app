import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { lessonsByOrder, challengesByOrder, examsByOrder } from "../src/data/lessons.js";

// Keep the authored curriculum as the only source of truth. The small catalog
// supports navigation/progress without downloading every exercise at startup.
export function courseMetadata({ blocks: _blocks, goals: _goals, quiz, questions, ...metadata }) {
  return { ...metadata, quizCount: quiz?.length ?? 0, questionCount: questions?.length ?? 0 };
}

export function catalogSource() {
  const header = "// Generated by node scripts/build-course-catalog.mjs. Do not edit by hand.\n";
  const arrays = Object.entries({ lessonsByOrder, challengesByOrder, examsByOrder })
    .map(([name, items]) => `export const ${name} = [\n${items.map(item => `  ${JSON.stringify(courseMetadata(item))}`).join(",\n")}\n];\n`)
    .join("\n");
  return header + arrays + `\nexport function pathOrderForPhase(phase) {\n  return lessonsByOrder.filter(item => item.phase === phase).at(-1)?.pathOrder ?? -1;\n}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL("../src/data/course-catalog.js", import.meta.url), catalogSource());
}
